export type TranslationKey = keyof typeof en;
export type Dictionary = Record<TranslationKey, string>;

export const LANGUAGES = [
  { code: 'en', label: 'English', locale: 'en-US' },
  { code: 'pl', label: 'Polski', locale: 'pl-PL' },
  { code: 'fr', label: 'Français', locale: 'fr-FR' },
] as const;

export type LanguageCode = (typeof LANGUAGES)[number]['code'];

/** English: in the app from the start — the source of truth and the fallback. */
export { en };

/** The other languages, each its own file — downloaded only when it's the one chosen. */
export const LOADERS: Record<Exclude<LanguageCode, 'en'>, () => Promise<Dictionary>> = {
  pl: () => import('./translations.pl').then((m) => m.pl),
  fr: () => import('./translations.fr').then((m) => m.fr),
};
